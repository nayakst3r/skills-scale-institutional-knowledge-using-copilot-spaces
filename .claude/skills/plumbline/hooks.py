"""Generate git hooks from the repository's actual stack — Lefthook (preferred) or plain .githooks.

The generated lefthook.yml runs, on every commit, the Plumbline gate plus the formatters, linters and type checkers the
project already declares (TypeScript, ESLint, Prettier, Biome, Ruff, Black, dotnet format) — only tools that are in a
manifest, never ones it guesses. Monorepos get one set of jobs per sub-project via Lefthook's `root`.
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

from . import gate

MARKER = "# Generated by `plumbline hooks` — regenerate with `plumbline hooks --write`."
TS_TEMPLATES = Path(__file__).resolve().parent / "templates" / "ts-hooks"
TS_RUN = "node .plumbline/hooks/run.mjs"
TS_OWNED = ["lib.mts", "pre-commit.mts", "commit-msg.mts", "pre-push.mts", "run.mjs", "lib.test.mts", "tsconfig.json"]


def is_typescript_repo(root: Path) -> bool:
    """TypeScript at the repo root (or TS hooks already set up)."""
    if (root / "plumbline.hooks.mts").exists() or (root / "tsconfig.json").exists():
        return True
    return "typescript" in (gate.declared_js_deps(root) or set())


HOOK_PATHS = [".plumbline", "plumbline.hooks.mts"]


def _exclude_from_project_tsconfig(root: Path, dry_run: bool) -> list[tuple[str, str]]:
    """The hooks have their own tsconfig (.plumbline/hooks). Keep them out of the project's typecheck, which may lack
    @types/node or .mts import settings. Only plain-JSON tsconfigs are edited; otherwise say what to add."""
    cfg = root / "tsconfig.json"
    if not cfg.exists():
        return []
    try:
        data = json.loads(cfg.read_text())
    except json.JSONDecodeError:
        return [("todo", 'tsconfig.json has comments, so it was not edited: add ".plumbline" and '
                         '"plumbline.hooks.mts" to its "exclude" (the hooks have their own tsconfig)')]
    include = data.get("include")
    broad = "files" not in data and (include is None or any(str(i).startswith(("*", ".", "**")) for i in include))
    excluded = set(data.get("exclude", []))
    if not broad or set(HOOK_PATHS) <= excluded:
        return []
    if not dry_run:
        # tsc drops its default excludes once "exclude" is set, so keep node_modules explicitly
        base = data.get("exclude", ["node_modules"])
        data["exclude"] = base + [p for p in HOOK_PATHS if p not in base]
        cfg.write_text(json.dumps(data, indent=2) + "\n")
    return [("update", 'tsconfig.json — exclude ".plumbline" and "plumbline.hooks.mts" (hooks have their own tsconfig)')]


def install_ts_hooks(root: Path, branch: str, dry_run: bool = False) -> list[tuple[str, str]]:
    """Vendor the TypeScript hook library (Plumbline-owned, refreshed) and the team policy file (created once)."""
    log = []
    dest = root / ".plumbline" / "hooks"
    for name in TS_OWNED:
        src, out = TS_TEMPLATES / ".plumbline" / "hooks" / name, dest / name
        log.append(("update" if out.exists() else "create", f".plumbline/hooks/{name}"))
        if not dry_run:
            dest.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, out)
    log += _exclude_from_project_tsconfig(root, dry_run)
    policy = root / "plumbline.hooks.mts"
    if policy.exists():
        log.append(("skip (exists)", "plumbline.hooks.mts — your team's policy is never overwritten"))
    else:
        strict = "false"
        cfg = root / "plumbline.toml"
        if cfg.exists() and "require_ai_trailer = true" in cfg.read_text():
            strict = "true"
        log.append(("create", "plumbline.hooks.mts (typed hook policy)"))
        if not dry_run:
            text = (TS_TEMPLATES / "plumbline.hooks.mts").read_text()
            policy.write_text(text.replace("__DEFAULT_BRANCH__", branch).replace("__REQUIRE_TRAILER__", strict))
    return log
SKIP_DIRS = {"node_modules", ".git", ".venv", "venv", "dist", "build", ".plumbline", ".claude"}


def _manifests(root: Path) -> list[Path]:
    found = []
    for pattern in ("package.json", "pyproject.toml", "requirements.txt", "*.csproj", "*.sln"):
        for p in root.rglob(pattern):
            rel = p.relative_to(root)
            if not (set(rel.parts[:-1]) & SKIP_DIRS) and len(rel.parts) <= 4:
                found.append(p)
    return found


def detect(root: Path) -> list[dict]:
    """-> one entry per sub-project: {"dir": "frontend", "tools": [...]}, root project first."""
    projects: dict[str, set[str]] = {}
    for m in _manifests(root):
        d = m.parent.relative_to(root).as_posix()
        tools = projects.setdefault(d, set())
        if m.name == "package.json":
            deps = gate.declared_js_deps(m.parent) or set()
            for dep, tool in (("typescript", "tsc"), ("eslint", "eslint"), ("prettier", "prettier"),
                              ("@biomejs/biome", "biome")):
                if dep in deps:
                    tools.add(tool)
            if (m.parent / "tsconfig.json").exists() and "typescript" in deps:
                tools.add("tsc")
        elif m.name in {"pyproject.toml", "requirements.txt"}:
            deps = gate.declared_python_deps(m.parent)
            if "ruff" in deps:
                tools.add("ruff")
            elif "black" in deps:
                tools.add("black")
            pp = m.parent / "pyproject.toml"
            if pp.exists() and "[tool.ruff" in pp.read_text(errors="ignore"):
                tools.add("ruff")
                tools.discard("black")
        elif m.suffix in {".csproj", ".sln"}:
            tools.add("dotnet-format")
    ordered = sorted(projects.items(), key=lambda kv: (kv[0] != ".", kv[0]))
    return [{"dir": d, "tools": sorted(t)} for d, t in ordered if t or d == "."]


VENDORED = [".plumbline/**", ".claude/skills/**"]  # Plumbline's own files: never lint/format them as project code


def _job(name: str, run: str, glob: str | None = None, root: str = ".", stage_fixed: bool = False,
         use_stdin: bool = False) -> list[str]:
    lines = [f"    - name: {name}", f"      run: {run}"]
    if stage_fixed and root == ".":  # formatters/linters operate on {staged_files}
        lines.append("      exclude:")
        lines += [f'        - "{g}"' for g in VENDORED]
    if use_stdin:
        lines.append("      use_stdin: true")
    if root != ".":
        lines.append(f"      root: {root}/")
    if glob:
        lines.append(f'      glob: "{glob}"')
    if stage_fixed:
        lines.append("      stage_fixed: true")
    return lines


def lefthook_yaml(root: Path, gate_cmd: str = "python3 .plumbline/plumbline.py", branch: str = "main",
                  typescript: bool | None = None) -> str:
    projects = detect(root)
    ts = is_typescript_repo(root) if typescript is None else typescript
    out = [MARKER, "# Local, personal overrides go in lefthook-local.yml (git-ignored).", "",
           "pre-commit:", "  parallel: true", "  skip:", "    - merge", "    - rebase", "  jobs:"]
    out += _job("plumbline-gate", f"{gate_cmd} --staged")
    if ts:
        out += _job("policy (typescript)", f"{TS_RUN} pre-commit")
    for p in projects:
        d, tools, tag = p["dir"], p["tools"], ("" if p["dir"] == "." else f" ({p['dir']})")
        js = "*.{js,jsx,ts,tsx,mjs,cjs}"
        if "biome" in tools:
            out += _job(f"biome{tag}", "npx biome check --write --no-errors-on-unmatched {staged_files}",
                        "*.{js,jsx,ts,tsx,json,css}", d, True)
        else:
            if "eslint" in tools:
                out += _job(f"eslint{tag}", "npx eslint --fix {staged_files}", js, d, True)
            if "prettier" in tools:
                out += _job(f"prettier{tag}", "npx prettier --write --ignore-unknown {staged_files}",
                            "*.{js,jsx,ts,tsx,mjs,cjs,json,css,scss,md,yml,yaml}", d, True)
        if "tsc" in tools:
            out += _job(f"typecheck{tag}", "npx tsc --noEmit", "*.{ts,tsx}", d)
        if "ruff" in tools:
            out += _job(f"ruff{tag}", "ruff check --fix {staged_files} && ruff format {staged_files}", "*.py", d, True)
        if "black" in tools:
            out += _job(f"black{tag}", "black {staged_files}", "*.py", d, True)
        if "dotnet-format" in tools:
            out += _job(f"dotnet-format{tag}", "dotnet format --include {staged_files}", "*.cs", d, True)
    out += ["", "commit-msg:", "  jobs:"]
    if ts:  # Conventional Commits + architecture scopes + provenance trailer, policy in plumbline.hooks.mts
        out += _job("commit-message (typescript)", f"{TS_RUN} commit-msg {{1}}")
    else:
        out += _job("ai-provenance-trailer", f"{gate_cmd} --commit-msg {{1}}")
    out += ["", "pre-push:", "  jobs:"]
    if ts:
        out += _job("protect-branches (typescript)", f"{TS_RUN} pre-push {{1}} {{2}}", use_stdin=True)
    out += _job("plumbline-gate-branch", f"{gate_cmd} --diff origin/{branch}")
    return "\n".join(out) + "\n"


def default_branch(root: Path) -> str:
    """origin's default branch if known, else the current branch, else main."""
    ref = subprocess.run(["git", "symbolic-ref", "--short", "refs/remotes/origin/HEAD"], cwd=root,
                         capture_output=True, text=True).stdout.strip()
    if ref.startswith("origin/"):
        return ref.split("/", 1)[1]
    for name in ("main", "master", "trunk"):
        if subprocess.run(["git", "rev-parse", "--verify", "-q", f"refs/heads/{name}"], cwd=root,
                          capture_output=True).returncode == 0:
            return name
    cur = subprocess.run(["git", "branch", "--show-current"], cwd=root, capture_output=True, text=True).stdout.strip()
    return cur or "main"


def lefthook_available(root: Path) -> str | None:
    """Return the command that runs lefthook here, or None."""
    if shutil.which("lefthook"):
        return "lefthook"
    if (root / "node_modules/.bin/lefthook").exists():
        return "npx lefthook"
    return None


def wants_lefthook(root: Path) -> bool:
    deps = gate.declared_js_deps(root) or set()
    return bool(lefthook_available(root) or "lefthook" in deps or "@evilmartians/lefthook" in deps
                or any((root / n).exists() for n in ("lefthook.yml", ".lefthook.yml", "lefthook.yaml")))


def install(root: Path) -> tuple[bool, str]:
    cmd = lefthook_available(root)
    if not cmd:
        return False, ("lefthook is not installed. Install it with one of: `npm install --save-dev lefthook`, "
                       "`pipx install lefthook`, `brew install lefthook`, `go install github.com/evilmartians/lefthook/v2@latest`, "
                       "then run `lefthook install`.")
    hooks_path = subprocess.run(["git", "config", "core.hooksPath"], cwd=root, capture_output=True, text=True).stdout.strip()
    if hooks_path == ".githooks":  # lefthook manages .git/hooks itself
        subprocess.run(["git", "config", "--unset", "core.hooksPath"], cwd=root, check=False)
    r = subprocess.run(cmd.split() + ["install"], cwd=root, capture_output=True, text=True)
    return r.returncode == 0, (r.stdout + r.stderr).strip()


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="plumbline hooks", description="Generate git hooks from the detected stack")
    ap.add_argument("--root", default=".")
    ap.add_argument("--write", action="store_true", help="write lefthook.yml (only if absent or generated by Plumbline)")
    ap.add_argument("--install", action="store_true", help="run `lefthook install` after writing")
    ap.add_argument("--force", action="store_true", help="overwrite a hand-written lefthook.yml")
    ap.add_argument("--gate-cmd", default="python3 .plumbline/plumbline.py")
    ap.add_argument("--branch", help="default branch for pre-push (detected if omitted)")
    ap.add_argument("--json", action="store_true", help="print the detected stack instead of YAML")
    ts = ap.add_mutually_exclusive_group()
    ts.add_argument("--typescript", dest="ts", action="store_true", default=None,
                    help="programmatic TypeScript hooks (policy in plumbline.hooks.mts); auto-detected by default")
    ts.add_argument("--no-typescript", dest="ts", action="store_false")
    a = ap.parse_args(argv)
    root = gate.repo_root(Path(a.root).resolve())
    if a.json:
        print(json.dumps({"projects": detect(root), "typescript_hooks": is_typescript_repo(root)}, indent=2))
        return 0
    branch = a.branch or default_branch(root)
    text = lefthook_yaml(root, a.gate_cmd, branch, a.ts)
    if not a.write:
        print(text, end="")
        return 0
    target = next((root / n for n in ("lefthook.yml", ".lefthook.yml", "lefthook.yaml") if (root / n).exists()),
                  root / "lefthook.yml")
    if target.exists() and MARKER not in target.read_text() and not a.force:
        print(f"plumbline: {target.name} was written by hand — not overwriting. Merge these jobs yourself, "
              f"or pass --force:\n\n{text}", file=sys.stderr)
        return 1
    target.write_text(text)
    print(f"plumbline: wrote {target.relative_to(root)}")
    if a.ts or (a.ts is None and is_typescript_repo(root)):
        for action, path in install_ts_hooks(root, branch):
            print(f"plumbline: {action} {path}")
    if a.install:
        ok, msg = install(root)
        print(msg)
        return 0 if ok else 1
    return 0
